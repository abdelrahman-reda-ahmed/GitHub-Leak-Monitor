#!/usr/bin/env python3
"""
disclosure.py - read-only lookup, never sends anything
"""
from safe_fetch import safe_fetch
from db import get_connection


def lookup_security_txt(domain):
    """Fetch security.txt through safe_fetch"""
    url = f'https://{domain}/.well-known/security.txt'
    content = safe_fetch(url)
    if content:
        return content[:1000]
    return None


def draft_disclosure_text(secret: dict, occurrences: list) -> str:
    """
    Uses exposure_state (not diff_status) when describing current exposure.
    Lists all affected repos/domains, states no exploitation performed.
    """
    text = "Subject: Potential secret exposure report\n\n"
    text += "Hello,\n\n"
    text += f"I am writing to report a potential exposure of a {secret.get('secret_type')} credential.\n\n"
    text += f"Type: {secret.get('secret_type')}\n"
    text += f"Preview (masked): {secret.get('masked_preview')}\n"
    text += f"Severity: {secret.get('severity')}\n"
    text += f"First seen: {secret.get('first_seen_at')}\n"
    text += f"Last seen: {secret.get('last_seen_at')}\n\n"
    
    if len(occurrences) > 1:
        text += f"Affected locations ({len(occurrences)}):\n"
        for o in occurrences:
            text += f"- {o.get('target')}/{o.get('file_path')} (state: {o.get('exposure_state', 'unknown')})\n"
    else:
        o = occurrences[0] if occurrences else {}
        text += f"Affected location: {o.get('target')}/{o.get('file_path')}\n"
        text += f"Exposure state: {o.get('exposure_state', 'unknown')}\n"
    
    text += "\nVerification guidance:\n"
    text += "- Review the above locations independently.\n"
    text += "- This report was generated by pattern matching only; no credential testing or exploitation was performed.\n"
    text += "- Rotate/revoke if confirmed as valid.\n\n"
    text += "Best regards,\n[Your name/contact]\n"
    return text


if __name__ == '__main__':
    print(lookup_security_txt('example.com'))
